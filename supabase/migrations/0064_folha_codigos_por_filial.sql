-- Códigos da Domínio por filial (pedido do usuário, 22/10/2026: "todos os códigos precisam estar igual filial por
-- filial"). Na Domínio cada CNPJ tem os próprios códigos de evento ("Feriado trabalhado" é 259 numa filial, 261 noutra,
-- 202 noutra…) e a própria ordem de colunas. Esta tabela guarda, por unidade, as colunas de evento da planilha
-- "RELAÇÃO DE VALORES PARA FOLHA DE PAGAMENTO" da contabilidade, na ordem: rótulo, código e o evento do sistema que
-- vai nela (null = coluna que a contabilidade tem e o sistema não usa — sai vazia). A planilha gerada pelo sistema
-- segue isto quando existe; sem linha aqui (ex.: Nazário), continua com os códigos gerais de folha_eventos.
-- Carga inicial: as 33 planilhas de 09/2026 que a contabilidade devolveu (só os códigos; os valores foram ignorados).
-- Nada existente é alterado: códigos das empresas (folha_empresas_dominio) e dos funcionários (matrícula) já batiam.

create table public.folha_eventos_filial (
  branch_id  uuid not null references public.branches(id) on delete cascade,
  coluna     smallint not null check (coluna between 1 and 30),
  rotulo     text not null check (length(btrim(rotulo)) between 1 and 60),
  codigo     integer not null check (codigo > 0),
  evento_id  uuid references public.folha_eventos(id) on delete set null,
  arquivo    text,
  updated_by uuid constraint folha_eventos_filial_updated_by_fkey references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (branch_id, coluna)
);
create unique index folha_eventos_filial_evento_uk on public.folha_eventos_filial (branch_id, evento_id) where evento_id is not null;
create index folha_eventos_filial_evento_idx on public.folha_eventos_filial (evento_id);

alter table public.folha_eventos_filial enable row level security;
create policy fevf_sel on public.folha_eventos_filial for select to authenticated
  using ((select private.sou_admin()) or (select private.tem_papel('rh')));
create policy fevf_ins on public.folha_eventos_filial for insert to authenticated
  with check ((select private.sou_admin()) or (select private.tem_papel('rh')));
create policy fevf_upd on public.folha_eventos_filial for update to authenticated
  using ((select private.sou_admin()) or (select private.tem_papel('rh')))
  with check ((select private.sou_admin()) or (select private.tem_papel('rh')));
create policy fevf_del on public.folha_eventos_filial for delete to authenticated
  using ((select private.sou_admin()) or (select private.tem_papel('rh')));

